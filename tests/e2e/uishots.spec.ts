import { expect, test } from '@playwright/test';
// Opt-in UI review captures: CD_UISHOTS=1 npx playwright test uishots
test.skip(!process.env.CD_UISHOTS, 'opt-in');
const SHOTS = 'qa-shots/ui/';
const state = (page: any) => page.evaluate(() => (window as any).__cd?.state);

test('garage, relief select, loading, HUD, photo', async ({ page }) => {
  test.setTimeout(300_000);
  await page.goto('/');
  await page.waitForTimeout(2500);
  await page.screenshot({ path: `${SHOTS}title.png` });
  await page.locator('[data-a="garage"]').click();
  await page.waitForTimeout(2500);
  await page.screenshot({ path: `${SHOTS}garage.png` });
  const drag = async (dx: number) => { await page.mouse.move(400, 400); await page.mouse.down(); await page.mouse.move(400 + dx, 400, { steps: 8 }); await page.mouse.up(); await page.waitForTimeout(1200); };
  await drag(190);
  await page.screenshot({ path: `${SHOTS}garage-side.png` });
  await drag(190);
  await page.screenshot({ path: `${SHOTS}garage-rear.png` });
  await page.locator('.gpanel [data-v="vireo"]').click();
  await page.waitForTimeout(1500);
  await page.screenshot({ path: `${SHOTS}garage-vireo.png` });
  await page.locator('.gpanel [data-v="m3c"]').click();
  await page.locator('.garage [data-a="back"]').click();
  await page.locator('[data-a="select"]').click();
  await page.waitForTimeout(3000);
  await page.screenshot({ path: `${SHOTS}select.png` });
  await page.locator('.card [data-j="la"]').click();
  await page.waitForTimeout(2500);
  await page.screenshot({ path: `${SHOTS}select-la.png` });
  await page.locator('.card [data-j="sf"]').click();
  await page.waitForTimeout(500);
  await page.locator('.card [data-a="drive"]').click();
  await page.waitForTimeout(700);
  await page.screenshot({ path: `${SHOTS}loading.png` });
  await expect.poll(() => state(page), { timeout: 200_000 }).toMatch(/reveal|drive/);
  await page.keyboard.press('KeyX');
  await expect.poll(() => state(page), { timeout: 30_000 }).toBe('drive');
  await expect.poll(() => page.evaluate(() => (window as any).__cd.pending), { timeout: 120_000 }).toBe(0);
  await page.keyboard.down('KeyW');
  await page.waitForTimeout(3200);
  await page.screenshot({ path: `${SHOTS}hud-accel.png` });
  await page.keyboard.up('KeyW');
  await page.keyboard.press('KeyF');
  await page.waitForTimeout(800);
  await page.locator('.photo-ui [data-g="lens"] [data-v="85"]').click();
  await page.locator('.photo-ui [data-g="dof"] [data-v="1.4"]').click();
  await page.locator('.photo-ui [data-g="lb"] [data-v="2.39"]').click();
  await page.waitForTimeout(1500);
  await page.screenshot({ path: `${SHOTS}photo-dof.png` });
});
